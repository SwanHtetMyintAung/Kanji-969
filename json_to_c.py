#!/usr/bin/env python3
"""
json_to_c.py - turn a JSON file into a C header that holds its text.

    python json_to_c.py input.json [output.h] [--name NAME] [--pretty]

The header defines two things (NAME defaults to the file name of the input,
made a valid C identifier):

    static const char NAME[] = { ... };   // the JSON text, UTF-8, ending in '\\0'
    static const int  NAME_size = N;      // its length in bytes, without the '\\0'

The text is stored as a char array, not as a "..." string literal, on purpose:
Visual C++ refuses string literals larger than about 64 KB (16 KB per piece),
and a kanji data file is far bigger than that. An array has no such limit, and
because it ends in '\\0' it can be given to cJSON_Parse as it is.

By default the JSON is minified (no spaces or line breaks) to make the
executable smaller; --pretty keeps the text exactly as it is in the file.
The file is checked to be valid UTF-8 JSON first, so a mistake in it is found
here and not when the program runs.
"""

import argparse
import json
import os
import re
import sys

BYTES_PER_LINE = 24


def c_identifier(text):
    ident = re.sub(r"[^0-9A-Za-z_]", "_", text)
    if not ident or ident[0].isdigit():
        ident = "_" + ident
    return ident


def read_json(path):
    """Returns (text, data): the file decoded as UTF-8 (a BOM is dropped) and parsed."""
    with open(path, "rb") as f:
        raw = f.read()
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError as error:
        sys.exit("error: %s is not valid UTF-8 (%s)" % (path, error))
    try:
        data = json.loads(text)
    except ValueError as error:
        sys.exit("error: %s is not valid JSON (%s)" % (path, error))
    return text, data


def make_payload(text, data, pretty):
    if pretty:
        return text.encode("utf-8")
    try:
        minified = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
        return minified.encode("utf-8")
    except UnicodeEncodeError:
        # a lone surrogate escape in the JSON: keep every non-ASCII character escaped
        return json.dumps(data, ensure_ascii=True, separators=(",", ":")).encode("utf-8")


def as_signed_char(value):
    # written as the value a (signed) char has, so that no compiler warns about
    # a constant that does not fit: 0xE9 becomes -23
    return value - 256 if value > 127 else value


def write_header(path, source_name, name, payload):
    guard = c_identifier(name).upper() + "_EMBEDDED_H"
    values = [str(as_signed_char(b)) for b in payload] + ["0"]
    lines = []
    for i in range(0, len(values), BYTES_PER_LINE):
        lines.append("    " + ", ".join(values[i:i + BYTES_PER_LINE]))
    body = ",\n".join(lines)

    with open(path, "w", newline="\n") as f:
        f.write("/* Generated by json_to_c.py from %s. Do not edit. */\n" % source_name)
        f.write("#ifndef %s\n#define %s\n\n" % (guard, guard))
        f.write("/* The JSON text (UTF-8), followed by a '\\0': cJSON_Parse can read it as it is. */\n")
        f.write("static const char %s[] = {\n%s\n};\n\n" % (name, body))
        f.write("/* Its length in bytes, without the final '\\0'. */\n")
        f.write("static const int %s_size = %d;\n\n" % (name, len(payload)))
        f.write("#endif /* %s */\n" % guard)


def main():
    parser = argparse.ArgumentParser(description="Turn a JSON file into a C header holding its text.")
    parser.add_argument("input", help="the JSON file")
    parser.add_argument("output", nargs="?", help="the header to write (default: <input name>_embedded.h)")
    parser.add_argument("-n", "--name", help="name of the C variable (default: the name of the input file)")
    parser.add_argument("--pretty", action="store_true", help="keep the JSON as written instead of minifying it")
    args = parser.parse_args()

    stem = os.path.splitext(os.path.basename(args.input))[0]
    name = c_identifier(args.name if args.name else stem)
    output = args.output if args.output else stem + "_embedded.h"

    text, data = read_json(args.input)
    payload = make_payload(text, data, args.pretty)
    if b"\x00" in payload:
        sys.exit("error: the JSON contains a NUL character, which a C string cannot hold")

    write_header(output, os.path.basename(args.input), name, payload)
    print("%s: %d bytes of JSON -> %s (%s, %s_size)" % (args.input, len(payload), output, name, name))


if __name__ == "__main__":
    main()
